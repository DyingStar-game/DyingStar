#!/usr/bin/env python3
"""Aggregate what the survey learnt about face sliders into assets/_universe/characters/human/face_stats.json.

    python3 stats.py <adults_fit.npz> <slider_trust.json> <ffhq features dir> <project root>

Only sliders that the survey recovers well on our own renders (correlation >= MIN_R, slider_trust.json) are
described; per slider: how far real faces go (`range`, what the slider's full travel reaches, in the bank's
units), and how real faces spread around the creator's neutral, per sex (`sd`, `female`, `male` offsets).
Absolute means are NOT kept: they are biased the same way for men and women (the photos' perspective), so
only the difference between the sexes is, split half each way. Nothing per photo leaves ~/datasets.
"""
import json
import os
import sys

import numpy as np

MIN_R = 0.68
MAX_SD = 0.8  # what a photo's brows or noise inflate is capped
OUT_REL = "assets/_universe/characters/human/face_stats.json"
CREDIT = ("NVIDIA - Flickr-Faces-HQ (FFHQ) - https://github.com/NVlabs/ffhq-dataset - CC BY-NC-SA 4.0\n"
          "Brno University of Technology (DCGM) - FFHQ features - https://github.com/DCGM/ffhq-features-dataset - CC BY-NC-SA 4.0\n")


def main():
    fit_path, trust_path, features, root = sys.argv[1:5]
    d = np.load(fit_path, allow_pickle=True)
    keys = list(d["keys"])
    trust = [t for t in json.load(open(trust_path)) if t["r"] >= MIN_R]
    cols = [keys.index(t["key"]) for t in trust]
    fix = np.array([t["sd_true"] / t["sd_fit"] for t in trust])
    w = d["weights"][:, cols]
    w = (w - w.mean(0)) * fix
    sex = np.array([json.load(open(os.path.join(features, os.path.basename(str(p))[:5] + ".json")))[0]["faceAttributes"]["gender"]
                    for p in d["paths"]])
    z = np.abs(w / w.std(0)).max(1)
    keep = z < np.percentile(z, 99)  # failed fits
    w, sex = w[keep], sex[keep]
    sliders = {}
    for j, t in enumerate(trust):
        men, women = w[sex == "male", j], w[sex == "female", j]
        half = (women.mean() - men.mean()) / 2.0
        sd = float(min(np.sqrt((men.var() * len(men) + women.var() * len(women)) / len(w)), MAX_SD))
        reach = float(np.percentile(np.abs(np.concatenate([men + half, women - half])), 99))
        sliders[t["key"]] = {"range": round(float(np.clip(reach, 1.0, 2.0)), 2), "sd": round(sd, 3),
                             "female": round(float(half), 3), "male": round(float(-half), 3)}
        print(f"{t['key']:38s} range {sliders[t['key']]['range']:.2f} sd {sd:.2f} women {half:+.2f}")
    out = {"_doc": "Generated by tools/character/face_survey/stats.py from the adult faces of FFHQ (aggregates only): "
                   "per creator slider, its reach (range: what the slider's full travel means, in the shape key's units) "
                   "and how real faces spread around the neutral, per sex (sd, female / male offsets, same units).",
           "faces": int(len(w)), "sliders": sliders}
    path = os.path.join(root, OUT_REL)
    json.dump(out, open(path, "w"), indent=1)
    open(os.path.splitext(path)[0] + ".txt", "w").write(CREDIT)
    print(f"{len(sliders)} sliders from {len(w)} faces -> {path}")


if __name__ == "__main__":
    sys.exit(main())

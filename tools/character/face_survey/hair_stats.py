#!/usr/bin/env python3
"""What hair real people wear, as the game's settings: assets/_universe/characters/human/hair_stats.json, which
CharacterAppearance.random() draws heads of hair and beards from. Aggregates only -- no photo, no person.

    python3 hair_stats.py <ffhq hair.npz> <library hair.npz> <library cuts.txt> <project root>

hair.npz files come from hair_measure.py: on FFHQ's adults, and on the library -- our own renders of random
heads of hair (test/character/human_preview.tscn --randcut, cuts.txt: "<batch> <head> <HairCut bytes hex>"),
measured the same way. A photo's settings are estimated from the library renders whose measures are nearest
to its own (heads facing the camera only, as the renders do); the estimates are then gathered, per sex and
age band, into a few families -- a typical cut and how often it is worn.

Beards and baldness are not measured on the renders: they come from ffhq-features' facialHair and bald scores.
"""
import json
import os
import sys

import numpy as np
from scipy.cluster.vq import kmeans2

OUT_REL = "assets/_universe/characters/human/hair_stats.json"
CREDIT = ("NVIDIA - Flickr-Faces-HQ (FFHQ) - https://github.com/NVlabs/ffhq-dataset - CC BY-NC-SA 4.0\n"
          "Brno University of Technology (DCGM) - FFHQ features - https://github.com/DCGM/ffhq-features-dataset - CC BY-NC-SA 4.0\n")
FEATURES = ("crown", "forehead", "fringe", "temples", "below_chin", "width", "coherence", "amount")
CUT_FIELDS = ("length", "sides", "volume", "curl", "density", "fringe", "recession", "crown_bald", "low_line")
CUT_BYTES = (0, 1, 2, 3, 4, 5, 6, 7, 10)  # each field's byte in HairCut.to_bytes (low_line: 0 in a 10-byte cut)
PART_BYTE, TIE_BYTE = 8, 9
PARTS, TIES = 7, 3  # HairCut.Part, HairCut.Tie
AGE_BANDS = ((18, 30), (30, 45), (45, 60), (60, 120))
FAMILIES = 8
NEIGHBOURS = 5
MAX_YAW = 20.0  # deg: the renders face the camera
# A photo reads less coherent than a render of the same hair (sensor noise, blur, highlights, stray hairs): our
# straight hair measures 0.72, FFHQ's median 0.62 though most of its adults wear straight hair. Added to the
# photos' coherence before they are matched.
PHOTO_COHERENCE_OFFSET = 0.12


def columns(npz):
    names = [str(c) for c in npz["columns"]]
    rows = npz["rows"]
    return {n: rows[:, k] for k, n in enumerate(names)}


def feature_matrix(col):
    x = np.stack([col[f] for f in FEATURES], 1).astype(np.float64)
    x[:, FEATURES.index("below_chin")] = np.clip(x[:, FEATURES.index("below_chin")], -3.0, 1.5)  # past the frame
    return x


def main():
    ffhq, lib = np.load(sys.argv[1]), np.load(sys.argv[2])
    cuts_path, root = sys.argv[3], sys.argv[4]
    real, ours = columns(ffhq), columns(lib)
    # Library: each measured tile's cut (its index in the measured set -> the tile name -> cuts.txt).
    tiles = [os.path.basename(str(p)) for p in np.load(sys.argv[2].replace("hair.npz", "lm.npz"), allow_pickle=True)["paths"]]
    cut_of = {}
    for line in open(cuts_path):
        batch, head, hexa = line.split()
        cut_of[f"b{batch}_{head}.png"] = bytes.fromhex(hexa)
    lib_cuts, known = [], []
    for i in lib["index"]:
        raw = cut_of.get(tiles[i])
        known.append(raw is not None)
        lib_cuts.append([(raw[b] if b < len(raw) else 0) / 255.0 for b in CUT_BYTES] + [raw[PART_BYTE], raw[TIE_BYTE]]
                        if raw is not None else [np.nan] * (len(CUT_FIELDS) + 2))
    lib_cuts = np.array(lib_cuts)
    x_lib = feature_matrix(ours)
    keep_lib = np.isfinite(x_lib).all(1) & np.array(known)
    x_lib, lib_cuts = x_lib[keep_lib], lib_cuts[keep_lib]
    x_real = feature_matrix(real)
    x_real[:, FEATURES.index("coherence")] += PHOTO_COHERENCE_OFFSET
    frontal = (np.abs(real["yaw"]) < MAX_YAW) & np.isfinite(x_real).all(1) & (real["amount"] > 0.05)
    mu, sd = x_real[frontal].mean(0), x_real[frontal].std(0) + 1e-9
    zl, zr = (x_lib - mu) / sd, (x_real[frontal] - mu) / sd
    # Each photo: the mean settings of its nearest renders (parts and ties: the nearest one's).
    d = ((zr[:, None, :] - zl[None, :, :]) ** 2).sum(2)
    near = np.argsort(d, 1)[:, :NEIGHBOURS]
    nf = len(CUT_FIELDS)
    est = lib_cuts[near, :nf].mean(1)
    part = lib_cuts[near[:, 0], nf]
    tie = lib_cuts[near[:, 0], nf + 1]
    print(f"{frontal.sum()} frontal photos matched to {len(zl)} renders; median distance "
          f"{np.median(np.sqrt(d[np.arange(len(d)), near[:, 0]])):.2f} sd")
    male, age = real["male"][frontal], real["age"][frontal]
    out = {"_doc": "Generated by tools/character/face_survey/hair_stats.py from FFHQ's adults (aggregates only): per "
                   "sex and age band, families of heads of hair (HairCut settings) and how often each is worn; beard "
                   "and baldness rates. Never edit by hand.",
           "fields": list(CUT_FIELDS), "age_bands": [list(b) for b in AGE_BANDS], "hair": {}, "beard": {}}
    rng = np.random.default_rng(5)
    for sex, name in ((1.0, "male"), (0.0, "female")):
        out["hair"][name] = []
        for lo, hi in AGE_BANDS:
            sel = (male == sex) & (age >= lo) & (age < hi)
            if sel.sum() < FAMILIES * 4:
                out["hair"][name].append([])
                continue
            centres, label = kmeans2(est[sel], FAMILIES, seed=int(rng.integers(1 << 30)), minit="++")
            families = []
            for k in range(FAMILIES):
                m = label == k
                if m.sum() == 0:
                    continue
                parts = np.bincount(part[sel][m].astype(int), minlength=PARTS)
                ties = np.bincount(tie[sel][m].astype(int), minlength=TIES)
                families.append({"weight": round(float(m.mean()), 3),
                                 "cut": [round(float(v), 3) for v in centres[k]],
                                 "spread": [round(float(v), 3) for v in est[sel][m].std(0)],
                                 "part": [round(float(v), 3) for v in parts / parts.sum()],
                                 "tie": [round(float(v), 3) for v in ties / ties.sum()]})
            out["hair"][name].append(families)
            print(f"{name} {lo}-{hi}: {sel.sum()} photos, families "
                  + ", ".join(f"{f['weight']:.2f} L{f['cut'][0]:.2f} C{f['cut'][3]:.2f}" for f in families))
    # Beards (men) and baldness by age, from ffhq-features over all the men (any pose).
    m_all = real["male"] == 1.0
    for lo, hi in AGE_BANDS:
        sel = m_all & (real["age"] >= lo) & (real["age"] < hi)
        b, mo, sb, bald = real["beard"][sel], real["moustache"][sel], real["sideburns"][sel], real["bald"][sel]
        out["beard"][f"{lo}-{hi}"] = {"beard": round(float(np.nanmean(b > 0.5)), 3), "moustache_only": round(float(np.nanmean((mo > 0.5) & (b <= 0.5))), 3),
                                      "stubble": round(float(np.nanmean((b > 0.2) & (b <= 0.5))), 3),
                                      "sideburns": round(float(np.nanmean(sb > 0.5)), 3), "bald": round(float(np.nanmean(bald > 0.5)), 3),
                                      "balding": round(float(np.nanmean((bald > 0.2) & (bald <= 0.5))), 3)}
        print(f"men {lo}-{hi}: {out['beard'][f'{lo}-{hi}']}")
    json.dump(out, open(os.path.join(root, OUT_REL), "w"), indent=1)
    open(os.path.join(root, os.path.splitext(OUT_REL)[0] + ".txt"), "w").write(CREDIT)
    print(f"-> {OUT_REL}")


if __name__ == "__main__":
    sys.exit(main())

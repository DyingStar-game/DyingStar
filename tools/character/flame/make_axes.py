#!/usr/bin/env python3
"""The creator's overall shape sliders, made from FLAME's identity directions.

    python3 make_axes.py <human_bank.npz> <corr.npz> <project root>

An axis is named by what it does (a wider face, a longer one, a squarer jaw...): a measure taken on the face's
landmarks (corr.npz: MediaPipe's points on our head), made relative to the distance between the eyes so that a
bigger head is not a wider face. Each FLAME direction changes that measure by some amount (it is linear in their
weights); the axis is the direction of real faces that changes it the most for the least improbable face -- the
measure's gradient over FLAME's directions, whose law is N(0, 1) -- so features that go together in real faces go
together on the axis. At full travel an axis is REACH deviations along that direction.

Writes assets/_universe/characters/human/face_axes.json, read by FaceAxes.
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "face_survey"))
from fit import Bank  # noqa: E402

REACH = 2.5  # deviations of real faces at an axis' full travel
FLAME_RANGE = 3.0  # CharacterAppearance.FLAME_RANGE: a FLAME slider's full travel
OUT_REL = "assets/_universe/characters/human/face_axes.json"

# MediaPipe landmark indices.
EYE_L, EYE_R = 468, 473  # irises' centres
CHEEK_L, CHEEK_R = 234, 454  # the face's sides at the cheekbones
JAW_L, JAW_R = 172, 397  # the jaw's corners
BROW_MID, CHIN = 9, 152
NOSE_TIP, NOSE_L, NOSE_R = 1, 98, 327
LIP_TOP, LIP_BOTTOM, MOUTH_L, MOUTH_R = 0, 17, 61, 291
BROW_RIDGE = (105, 334)
EYE_UPPER = (159, 386)


def dist(p, a, b):
    return np.linalg.norm(p[a] - p[b])


# id, label, measure(points) -> float (larger = the axis' "+" side)
MEASURES = [
    ("width", "%%CHAR_AXIS_WIDTH", lambda p: dist(p, CHEEK_L, CHEEK_R) / dist(p, EYE_L, EYE_R)),
    ("length", "%%CHAR_AXIS_LENGTH", lambda p: (p[BROW_MID, 1] - p[CHIN, 1]) / dist(p, EYE_L, EYE_R)),
    ("jaw", "%%CHAR_AXIS_JAW", lambda p: dist(p, JAW_L, JAW_R) / dist(p, CHEEK_L, CHEEK_R)),
    ("features", "%%CHAR_AXIS_FEATURES",
     lambda p: (np.mean([p[i, 2] for i in BROW_RIDGE]) - np.mean([p[i, 2] for i in EYE_UPPER])) / dist(p, EYE_L, EYE_R)),
    ("profile", "%%CHAR_AXIS_PROFILE",
     lambda p: (p[NOSE_TIP, 2] + p[CHIN, 2] - p[CHEEK_L, 2] - p[CHEEK_R, 2]) / dist(p, EYE_L, EYE_R)),
    ("mouth", "%%CHAR_AXIS_MOUTH", lambda p: (p[LIP_TOP, 1] - p[LIP_BOTTOM, 1]) / dist(p, MOUTH_L, MOUTH_R)),
    ("nose", "%%CHAR_AXIS_NOSE",
     lambda p: (dist(p, NOSE_L, NOSE_R) + (p[NOSE_TIP, 2] - 0.5 * (p[CHEEK_L, 2] + p[CHEEK_R, 2]))) / dist(p, EYE_L, EYE_R)),
    ("eyes", "%%CHAR_AXIS_EYES", lambda p: (dist(p, 159, 145) + dist(p, 386, 374)) / dist(p, EYE_L, EYE_R)),
]


def main():
    bank = Bank(sys.argv[1])
    corr = np.load(sys.argv[2])
    root = sys.argv[3]
    keys = [k for k in bank.names if k.startswith("FLAME_Identity_")]

    def landmarks(points):
        return (points[corr["vertices"]] * corr["bary"][..., None]).sum(1)

    base = landmarks(bank.base.astype(np.float64))
    moved = [landmarks(bank.base.astype(np.float64) + bank.target(k)) for k in keys]  # one deviation along each
    axes = []
    for axis_id, label, measure in MEASURES:
        m0 = measure(base)
        g = np.array([measure(p) - m0 for p in moved])  # the measure's change per deviation, per direction
        direction = g / np.linalg.norm(g)
        shares = direction * REACH / FLAME_RANGE  # stored slider values at the axis' full travel
        top = np.argsort(-np.abs(direction))[:3]
        print(f"{axis_id:9s} {m0:+.3f} -> +-{np.linalg.norm(g) * REACH:.3f} at full travel; mostly "
              + ", ".join(f"{keys[i][-2:]} {direction[i]:+.2f}" for i in top))
        axes.append({"id": axis_id, "label": label,
                     "shares": {k: round(float(s), 4) for k, s in zip(keys, shares) if abs(s) > 1e-3}})
    out = {"_doc": "Generated by tools/character/flame/make_axes.py: the creator's overall shape sliders, each a direction "
                   "of FLAME's real-face space (shares = stored slider values at the axis' full travel). Never edit by hand.",
           "axes": axes}
    json.dump(out, open(os.path.join(root, OUT_REL), "w"), indent=1)
    print(f"{len(axes)} axes -> {OUT_REL}")


if __name__ == "__main__":
    sys.exit(main())
